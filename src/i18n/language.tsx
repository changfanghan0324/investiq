export const catalogs: Record<Language, Catalog> = { en, "zh-CN": zhCN };

export const supportedLanguages: readonly Language[] = languageOptions.map((option) => option.code);

export type Translate = (key: TranslationKey, params?: Record<string, string | number>) => string;

interface LanguageContextValue {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  fontScale: FontScale;
  setFontScale: (fontScale: FontScale) => void;
  t: Translate;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);
// Display preferences persist per browser under the shared `investiq-` key namespace.
const STORAGE_KEY = "investiq-language";
const FONT_SCALE_STORAGE_KEY = "investiq-font-scale";

export function isLanguage(value: string | null): value is Language {
  return value === "en" || value === "zh-CN";
}

export function isFontScale(value: string | null): value is FontScale {
  return value === "25" || value === "50" || value === "75" || value === "100";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(defaultLanguage);
  const [fontScale, setFontScaleState] = useState<FontScale>(defaultFontScale);

  useEffect(() => {
    const restoreLanguage = window.setTimeout(() => {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (isLanguage(saved)) setLanguageState(saved);
      const savedFontScale = window.localStorage.getItem(FONT_SCALE_STORAGE_KEY);
      if (isFontScale(savedFontScale)) setFontScaleState(savedFontScale);
    });
    return () => window.clearTimeout(restoreLanguage);
  }, []);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  const setFontScale = useCallback((next: FontScale) => {
    setFontScaleState(next);
    window.localStorage.setItem(FONT_SCALE_STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    const selectedScale = fontScaleOptions.find((option) => option.value === fontScale) ?? fontScaleOptions[0];
    document.documentElement.dataset.fontScale = fontScale;
    document.documentElement.style.setProperty("--ui-font-scale", String(selectedScale.multiplier));
  }, [fontScale]);

  const t = useCallback<Translate>((key, params) => {
    let value: string = catalogs[language][key] ?? en[key];
    Object.entries(params ?? {}).forEach(([name, replacement]) => {
      value = value.replaceAll(`{${name}}`, String(replacement));
    });
    return value;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    fontScale,
    language,
    locale: language === "zh-CN" ? "zh-CN" : "en-US",
    setFontScale,
    setLanguage,
    t,
  }), [fontScale, language, setFontScale, setLanguage, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
